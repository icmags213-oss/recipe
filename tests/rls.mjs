import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
const A = '11111111-1111-4111-8111-111111111111';
const B = '22222222-2222-4222-8222-222222222222';
await db.exec(`create role anon; create role authenticated; create schema auth;
  create table auth.users(id uuid primary key);
  insert into auth.users values ('${A}'),('${B}');
  create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
  grant usage on schema public,auth to anon,authenticated;
  grant execute on function auth.uid() to anon,authenticated;`);
await db.exec(fs.readFileSync(new URL('../supabase/schema.sql',import.meta.url),'utf8'));
async function asUser(uid,sql) {
  await db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub','${uid}',false);`);
  return db.query(sql);
}
await asUser(A,`insert into public.recipe_entries values ('${A}','one','{"title":"Soup"}');`);
await asUser(A,`update public.recipe_entries set data='{"title":"Stew"}' where id='one';`);
assert.equal((await asUser(A,'select data from public.recipe_entries')).rows[0].data.title,'Stew');
assert.equal((await asUser(B,'select * from public.recipe_entries')).rows.length,0);
assert.equal((await asUser(B,"update public.recipe_entries set data='{}' where id='one' returning *")).rows.length,0);
assert.equal((await asUser(B,"delete from public.recipe_entries where id='one' returning *")).rows.length,0);
await assert.rejects(asUser(B,`insert into public.recipe_entries values ('${A}','evil','{}')`),/row-level security/);
await assert.rejects(asUser(A,`update public.recipe_entries set user_id='${B}' where id='one'`),/row-level security/);
await asUser(A,`insert into public.recipe_preferences values ('${A}','plan','{"today":["one"]}')`);
assert.equal((await asUser(B,'select * from public.recipe_preferences')).rows.length,0);
await assert.rejects(asUser(B,`insert into public.recipe_preferences values ('${A}','plan','{}')`),/row-level security/);
await assert.rejects(asUser(A,`update public.recipe_preferences set user_id='${B}'`),/row-level security/);
await asUser(B,`select public.recipe_import_device('[{"id":"local","title":"Pasta"}]','{"fridge":[]}');`);
assert.equal((await asUser(B,'select * from public.recipe_entries')).rows.length,1);
await assert.rejects(asUser(B,`select public.recipe_import_device('[{"id":"second"}]','{}')`),/already contains/);
assert.equal((await asUser(B,'select * from public.recipe_entries')).rows.length,1);
await db.exec('reset role; set role anon;');
await assert.rejects(db.query('select * from public.recipe_entries'),/permission denied/);
await assert.rejects(db.query('select * from public.recipe_preferences'),/permission denied/);
await assert.rejects(db.query("select public.recipe_import_device('[]','{}')"),/permission denied/);
await db.close();
console.log('RLS passed: owner CRUD, cross-user isolation, ownership reassignment, anonymous denial, atomic import.');
